// One-time generator: turns Natural Earth 110m land polygons into a single SVG
// path string in the same equirectangular projection UpcomingMap.astro uses
// (x = lon + 180, y = 90 - lat, viewBox 360x180).
//
// Run manually, not from prebuild — the output is committed so the site build
// has no network dependency and no geo library at runtime:
//
//   node scripts/gen-world-path.mjs
//
// Source: https://github.com/nvkelso/natural-earth-vector (public domain, CC0).

import fs from 'node:fs/promises';

const SRC =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson';
const OUT = 'src/lib/worldLand.ts';

// 1 decimal place on a 360x180 viewBox is ~0.1° — well below the visible
// resolution of a map this size, and it roughly halves the output.
const round = (n) => Math.round(n * 10) / 10;

function ringToPath(ring) {
  const pts = [];
  let prev = null;
  for (const [lon, lat] of ring) {
    const x = round(lon + 180);
    const y = round(90 - lat);
    // Drop consecutive duplicates introduced by rounding.
    if (prev && prev[0] === x && prev[1] === y) continue;
    pts.push([x, y]);
    prev = [x, y];
  }
  if (pts.length < 3) return '';
  return `M${pts.map(([x, y]) => `${x} ${y}`).join('L')}Z`;
}

const res = await fetch(SRC);
if (!res.ok) throw new Error(`fetch failed: HTTP ${res.status}`);
const geo = await res.json();

const paths = [];
for (const feature of geo.features) {
  const g = feature.geometry;
  const polygons =
    g.type === 'Polygon' ? [g.coordinates]
    : g.type === 'MultiPolygon' ? g.coordinates
    : [];
  for (const polygon of polygons) {
    for (const ring of polygon) {
      const d = ringToPath(ring);
      if (d) paths.push(d);
    }
  }
}

const d = paths.join('');
const file = `// GENERATED by scripts/gen-world-path.mjs — do not edit by hand.
//
// Natural Earth 110m land, public domain (CC0), projected equirectangularly
// onto a 360x180 viewBox: x = lon + 180, y = 90 - lat.
// Regenerate with: node scripts/gen-world-path.mjs
export const WORLD_LAND_PATH =
  '${d}';
`;

await fs.writeFile(OUT, file);
console.log(
  `[gen-world-path] ${geo.features.length} features → ${paths.length} rings, ` +
    `${(d.length / 1024).toFixed(1)}KB path → ${OUT}`,
);
